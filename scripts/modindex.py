#!/usr/bin/env python3
"""Generate docs/Modules.md (module index) from the leading comments of src/QBS.agda and src/QBS/**/*.agda, and lint:
every module must have a leading comment, and modules using `lem`/`funext` are flagged.
Usage: scripts/modindex.py [--check]   (--check: exit 1 if a header is missing or Modules.md is stale)"""
import os, re, sys

SRC = os.path.join(os.path.dirname(__file__), '..', 'src')
OUT = os.path.join(os.path.dirname(__file__), '..', 'docs', 'Modules.md')

def header(lines):
    """The leading `--` comment block (after the OPTIONS pragma, before code)."""
    c, started = [], False
    for l in lines:
        s = l.strip()
        if s.startswith('{-#') or (s == '' and not started):
            continue
        if s.startswith('--'):
            c.append(s.lstrip('-').strip()); started = True
        elif s.startswith('module') and not started:
            continue
        else:
            break
    return [x for x in c if x]

def sentence(h):
    """First sentence of a header (lines joined), at most 220 characters."""
    t = ' '.join(h)
    m = re.search(r'\.(\s|$)', t)
    t = t[:m.start() + 1] if m else t
    return t if len(t) <= 220 else t[:217] + '...'

def collect():
    rows = []
    files = [os.path.join(SRC, 'QBS.agda')]
    for d, _, fs in os.walk(os.path.join(SRC, 'QBS')):
        files += [os.path.join(d, f) for f in fs if f.endswith('.agda')]
    for p in files:
        text = open(p).read(); lines = text.split('\n')
        mod = os.path.relpath(p, SRC)[:-5].replace(os.sep, '.')
        h = header(lines)
        code = re.sub(r'--.*', '', text)
        hyp = [k for k, pat in (('lem', r'\blem[₁]?\b|\blemOf\b'), ('funext', r'\bfunext\b')) if re.search(pat, code)]
        rows.append((mod, len(lines), h, hyp))
    return sorted(rows)

def render(rows):
    layers = [('QBS.Model', 'Discrete model'), ('QBS.Borel', 'Borel structure on Cantor space'),
              ('QBS.Analysis', 'Analysis'), ('QBS.Continuous', 'Continuous model'), ('QBS.Example', 'Examples')]
    out = ['# Module index', '',
           '_Generated by `scripts/modindex.py` from the leading comment of each module; do not edit by hand._', '',
           'Column `hyp`: the module mentions `lem` (excluded middle) or `funext` directly; hypotheses also arrive',
           'through imports (see `Classical.md`).  The first sentence of the header is shown; read the file for the rest.', '']
    groups = {}
    for r in rows:
        g = 'Overview' if r[0] == 'QBS' else next((n for pre, n in layers if r[0].startswith(pre + '.')), 'Abstract layer')
        groups.setdefault(g, []).append(r)
    for g in ['Overview', 'Abstract layer'] + [n for _, n in layers]:
        if g not in groups: continue
        out += [f'## {g}', '', '| module | lines | hyp | purpose |', '|---|---|---|---|']
        for mod, n, h, hyp in groups[g]:
            first = sentence(h) if h else '**(no header)**'
            first = first.replace('|', '\\|')
            out.append(f'| `{mod}` | {n} | {", ".join(hyp)} | {first} |')
        out.append('')
    return '\n'.join(out)

if __name__ == '__main__':
    rows = collect(); md = render(rows)
    missing = [r[0] for r in rows if not r[2]]
    if '--check' in sys.argv:
        bad = False
        if missing: print('modules without a header comment:', *missing, sep='\n  '); bad = True
        if not os.path.exists(OUT) or open(OUT).read() != md + '\n': print('docs/Modules.md is stale: run scripts/modindex.py'); bad = True
        sys.exit(1 if bad else 0)
    open(OUT, 'w').write(md + '\n'); print(f'{len(rows)} modules, {len(missing)} without header')
